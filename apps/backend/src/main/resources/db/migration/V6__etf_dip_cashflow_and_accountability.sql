    tech_core_amount DECIMAL(24,8) NOT NULL,
    international_core_amount DECIMAL(24,8) NOT NULL,
    tactical_reserve_amount DECIMAL(24,8) NOT NULL,
    quality_opportunity_amount DECIMAL(24,8) NOT NULL,
    rule_ids JSON NOT NULL,
    evidence_checksum CHAR(64) NOT NULL,
    data_as_of DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_cashflow_allocation (user_id, strategy_version, allocation_month, evidence_checksum),
    CONSTRAINT fk_cashflow_allocation_user FOREIGN KEY (user_id) REFERENCES app_user (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

