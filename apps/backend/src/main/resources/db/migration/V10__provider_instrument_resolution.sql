ALTER TABLE position
    ADD COLUMN data_readiness VARCHAR(32) NOT NULL DEFAULT 'WAIT_FOR_DATA',
    ADD CONSTRAINT chk_position_data_readiness CHECK (data_readiness IN ('RESOLVED', 'WAIT_FOR_DATA'));

CREATE TABLE instrument_alias (
    alias_symbol VARCHAR(32) NOT NULL,
    instrument_id BINARY(16) NOT NULL,
    source VARCHAR(32) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (alias_symbol),
    CONSTRAINT fk_instrument_alias_instrument FOREIGN KEY (instrument_id) REFERENCES instrument (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE instrument_manual_mapping (
    user_id BINARY(16) NOT NULL,
    alias_symbol VARCHAR(32) NOT NULL,
    instrument_id BINARY(16) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (user_id, alias_symbol),
    CONSTRAINT fk_manual_mapping_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_manual_mapping_instrument FOREIGN KEY (instrument_id) REFERENCES instrument (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

